#!/usr/bin/env python3
"""Generate the ten bounded, read-only Cyber Sec GitHub Actions workers."""

import argparse
from pathlib import Path

CHECKOUT = "11bd71901bbe5b1630ceea73d27597364c9af683"
UPLOAD = "ea165f8d65b6e75b540449e92b4886f43607fa02"
WORKERS = {
    "security": "Security pattern triage",
    "bugs": "Known bug patterns",
    "regression": "Integrated regressions",
    "compatibility": "Protocol compatibility",
    "privacy": "Sensitive logging and state",
    "dependencies": "Dependency inventory and advisories",
    "workflows": "Workflow permission and trigger review",
    "build": "Java build and configuration syntax",
    "performance": "Streaming queue performance",
    "fuzz": "Bounded parser mutation checks",
}


def render():
    files = {}
    for number, (field, label) in enumerate(WORKERS.items(), 1):
        matrix = "\n    strategy:\n      fail-fast: false\n      matrix:\n        java: ['17', '21']" if field == "build" else ""
        java_version = "${{ matrix.java }}" if field == "build" else "17"
        online = " --online" if field == "dependencies" else ""
        text = """# Generated by tests/audit/workflow_definitions.py; review changes to both files.
name: Cyber Sec - LABEL

on:
  pull_request:
  push:
    branches: [master, main]
  workflow_dispatch:
  schedule:
    - cron: 'MINUTE 3 * * 6'

permissions:
  contents: read

concurrency:
  group: ${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: true

jobs:
  audit:
    runs-on: ubuntu-24.04
    timeout-minutes: 20MATRIX
    steps:
      - name: Checkout reviewed source
        uses: actions/checkout@CHECKOUT
        with:
          persist-credentials: false
      - name: Select installed JDK
        env:
          AUDIT_JAVA_VERSION: 'JAVA_VERSION_VALUE'
        run: |
          case "$AUDIT_JAVA_VERSION" in
            17) task_java_home="${JAVA_HOME_17_X64:-}" ;;
            21) task_java_home="${JAVA_HOME_21_X64:-}" ;;
            *) exit 1 ;;
          esac
          test -n "$task_java_home"
          test -x "$task_java_home/bin/javac"
          echo "$task_java_home/bin" >> "$GITHUB_PATH"
      - name: Test the audit tooling
        run: python3 -m unittest discover -s tests/audit -p 'test_*.py'
      - name: Run bounded audit
        run: python3 tests/audit/audit.py FIELD --output tests/results/FIELDONLINE
      - name: Retain audit evidence
        if: always()
        uses: actions/upload-artifact@UPLOAD
        with:
          name: cybersec-FIELD-jdk-JAVA_VERSION_VALUE
          path: tests/results/FIELD/
          if-no-files-found: warn
          retention-days: 7
"""
        for token, value in (("LABEL", label), ("MINUTE", str(number)), ("MATRIX", matrix),
                             ("JAVA_VERSION_VALUE", java_version), ("CHECKOUT", CHECKOUT),
                             ("UPLOAD", UPLOAD), ("FIELD", field), ("ONLINE", online)):
            text = text.replace(token, value)
        files["cybersec-" + field + ".yml"] = text
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / ".github/workflows"
    for name, text in render().items():
        path = directory / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit("Generated workflow differs: " + name)
        else:
            path.write_text(text)


if __name__ == "__main__":
    main()
